import { ARTICLE_TOPIC_LABELS, mediaForTopic, type ArticleTopic } from "@/lib/article-media-catalog";
import { bangkokMorning } from "@/lib/article-types";
import { clampSeoTitle, fitSeoDescription } from "@/lib/seo-limits";

export type PlannedArticle = {
  slug: string;
  title: string;
  excerpt: string;
  body: string;
  coverUrl: string;
  category: ArticleTopic;
  categoryName: string;
  seoTitle: string;
  metaDescription: string;
  keywords: string;
  publishAt: Date;
};

const QUEUE_START_UTC = Date.UTC(2026, 8, 25);

export function queuePublishAt(offsetDays: number): Date {
  const day = new Date(QUEUE_START_UTC + offsetDays * 24 * 60 * 60 * 1000);
  return bangkokMorning(day.getUTCFullYear(), day.getUTCMonth() + 1, day.getUTCDate());
}

function post(input: {
  day: number;
  category: ArticleTopic;
  slug: string;
  title: string;
  excerpt: string;
  seoTitle: string;
  metaDescription: string;
  keywords: string;
  sections: Array<{ h: string; level?: 2 | 3; p?: string; quote?: string; items?: string[] }>;
}): PlannedArticle {
  const body = input.sections
    .map((section) => {
      const tag = section.level === 3 ? "h3" : "h2";
      const chunks = [`<${tag}>${section.h}</${tag}>`];
      if (section.p) chunks.push(`<p>${section.p}</p>`);
      if (section.quote) chunks.push(`<blockquote>${section.quote}</blockquote>`);
      for (const item of section.items || []) chunks.push(`<li>${item}</li>`);
      return chunks.join("\n");
    })
    .join("\n");
  return {
    slug: input.slug,
    title: input.title,
    excerpt: input.excerpt.slice(0, 180),
    body,
    coverUrl: mediaForTopic(input.category).coverUrl,
    category: input.category,
    categoryName: ARTICLE_TOPIC_LABELS[input.category],
    seoTitle: clampSeoTitle(input.seoTitle),
    metaDescription: fitSeoDescription(input.metaDescription),
    keywords: input.keywords,
    publishAt: queuePublishAt(input.day),
  };
}

