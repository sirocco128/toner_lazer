export function isIdeaThemeSlug(value: string): value is IdeaThemeSlug {
  return (IDEA_THEME_SLUGS as readonly string[]).includes(value);
}

export function getIdeaTheme(slug: string): IdeaTheme | null {
  if (!isIdeaThemeSlug(slug)) return null;
  return IDEA_THEMES.find((theme) => theme.slug === slug) ?? null;
}

export function ideaThemePath(slug: IdeaThemeSlug): string {
  return `/ideas/${slug}`;
}
