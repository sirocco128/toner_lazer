#!/usr/bin/env node
/**
 * Generate an env file from approved Sprint 2 intake JSON.
 *
 *   node scripts/apply-sprint2-intake.mjs --target .env.staging
 *   node scripts/apply-sprint2-intake.mjs --target .env.staging --dry-run
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  DEFAULT_INTAKE_PATH,
  loadIntake,
  asFieldSection,
  fieldValue,
  fieldReady,
  ROOT,
} from "./sprint2-intake-lib.mjs";

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const targetIdx = args.indexOf("--target");
const intakeIdx = args.indexOf("--intake");

if (targetIdx < 0 || !args[targetIdx + 1]) {
  console.error("Usage: apply-sprint2-intake.mjs --target <env-file> [--intake path] [--dry-run]");
  process.exit(1);
}

const targetPath = resolve(ROOT, args[targetIdx + 1]);
const intakePath = intakeIdx >= 0 ? args[intakeIdx + 1] : DEFAULT_INTAKE_PATH;

const REQUIRED = [
  ["business", "brandName"],
  ["business", "phoneDisplay"],
  ["business", "phoneHref"],
  ["business", "email"],
  ["technical", "siteUrl"],
  ["technical", "ipHashSecret"],
];

function envLine(key, value) {
  const safe = String(value).replace(/\n/g, " ").trim();
  if (/[\s#"'\\]/.test(safe)) {
    return `${key}="${safe.replace(/"/g, '\\"')}"`;
  }
  return `${key}=${safe}`;
}

function main() {
  const { data } = loadIntake(intakePath);
  const business = asFieldSection(data.business);
  const technical = asFieldSection(data.technical);
  const gates = asFieldSection(data.gates);

  /** @type {string[]} */
  const blockers = [];
  for (const [sectionName, key] of REQUIRED) {
    const section = sectionName === "business" ? business : technical;
    if (!fieldReady(section[key], { requireApproved: true })) {
      blockers.push(`${sectionName}.${key}`);
    }
  }

  if (blockers.length > 0) {
    console.error("Cannot apply intake — fields must be status APPROVED with values:");
    for (const b of blockers) console.error(`  - ${b}`);
    process.exit(1);
  }

  const allowIndexing = fieldValue(gates.allowIndexing) === true;
  const legalApproved = fieldValue(gates.legalContentApproved) === true;
  const assetsApproved = fieldValue(gates.realAssetsApproved) === true;

  if (allowIndexing && (!legalApproved || !assetsApproved)) {
    console.error(
      "Refusing allowIndexing=true without legalContentApproved and realAssetsApproved.",
    );
    process.exit(1);
  }

  const cmsMode = fieldValue(technical.cmsMode) || "strapi";
  const lines = [
    "# Generated by npm run sprint2:apply-intake — do not commit if it contains secrets",
    `# source: ${intakePath}`,
    `# generated: ${new Date().toISOString()}`,
    "",
    envLine("NEXT_PUBLIC_SITE_URL", fieldValue(technical.siteUrl)),
    envLine("NEXT_PUBLIC_SITE_NAME", fieldValue(business.brandName)),
    envLine("NEXT_PUBLIC_SITE_DESCRIPTION", fieldValue(business.siteDescription)),
    envLine("NEXT_PUBLIC_SITE_PHONE_DISPLAY", fieldValue(business.phoneDisplay)),
    envLine("NEXT_PUBLIC_SITE_PHONE_HREF", fieldValue(business.phoneHref)),
    envLine("NEXT_PUBLIC_SITE_EMAIL", fieldValue(business.email)),
    envLine("NEXT_PUBLIC_LINE_ID", fieldValue(business.lineId)),
    envLine("NEXT_PUBLIC_LINE_URL", fieldValue(business.lineUrl)),
    envLine("NEXT_PUBLIC_ALLOW_INDEXING", allowIndexing ? "true" : "false"),
    envLine("NEXT_PUBLIC_ENABLE_P2_QUOTE_TOOLS", "false"),
    "",
    envLine("LEGAL_CONTENT_APPROVED", legalApproved ? "true" : "false"),
    envLine("REAL_ASSETS_APPROVED", assetsApproved ? "true" : "false"),
    envLine("RUNTIME_SECRETS_APPROVED", "true"),
    "",
    envLine("SITE_LEGAL_NAME", fieldValue(business.legalName)),
    envLine("SITE_TAX_ID", fieldValue(business.taxId)),
    envLine(
      "SITE_ENABLE_LOCAL_BUSINESS_SCHEMA",
      fieldValue(business.streetAddress) ? "true" : "false",
    ),
    envLine("SITE_BUSINESS_TYPE", "ProfessionalService"),
    envLine("SITE_STREET_ADDRESS", fieldValue(business.streetAddress)),
    envLine("SITE_ADDRESS_LOCALITY", fieldValue(business.addressLocality)),
    envLine("SITE_ADDRESS_REGION", fieldValue(business.addressRegion)),
    envLine("SITE_POSTAL_CODE", fieldValue(business.postalCode)),
    envLine("SITE_COUNTRY_CODE", fieldValue(business.countryCode) || "TH"),
    envLine("SITE_OPENING_HOURS", fieldValue(business.openingHours)),
    "",
    envLine("CMS_MODE", cmsMode),
    envLine("STRAPI_URL", fieldValue(technical.strapiUrl)),
    envLine("STRAPI_API_TOKEN", fieldValue(technical.strapiApiToken)),
    envLine("STRAPI_PUBLIC_READ", "false"),
    envLine("STRAPI_FALLBACK_TO_MOCK", "false"),
    envLine("STRAPI_FETCH_TIMEOUT_MS", "8000"),
    envLine("NEXT_IMAGE_REMOTE_URLS", fieldValue(technical.nextImageRemoteUrls)),
    "",
    envLine("REVALIDATE_SECRET", fieldValue(technical.revalidateSecret)),
    envLine("IP_HASH_SECRET", fieldValue(technical.ipHashSecret)),
    "",
    "LEAD_STORAGE_MODE=sqlite",
    "SQLITE_PATH=.data/leads.sqlite",
    "ALLOW_FILE_LEAD_STORAGE=false",
    "QUOTE_RATE_LIMIT_MAX=5",
    "QUOTE_RATE_LIMIT_WINDOW_MINUTES=15",
    "",
  ];

  const body = `${lines.join("\n")}\n`;

  if (dryRun) {
    console.log(body);
    console.log("(dry-run — file not written)");
    return;
  }

  writeFileSync(targetPath, body, "utf8");
  console.log(`Wrote ${targetPath}`);
  console.log("Next: npm run staging:smoke (local) or deploy per docs/STAGING-DEPLOY.md");
}

main();
